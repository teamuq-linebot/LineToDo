import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = process.cwd()
const promptPath = 'src/main/features/groupTopics/prompts/chat-classify.md'
const schemaPath = 'src/main/features/groupTopics/prompts/topic-output.schema.json'
const outputPath = 'src/main/features/groupTopics/prompts/bundle.ts'
const combinedSectionPath = 'src/main/features/groupTopics/prompts/combined-topic-section.md'
const combinedSchemaPath = 'src/main/features/groupTopics/prompts/combined-output.schema.json'
const todoSchemaSourcePath = 'src/main/llm/schema.ts'
const combinedPromptVersion = 'extract-combined-v2'
const combinedSchemaVersion = 'extract-combined-schema-v2'
const hash = (path, bytes) => createHash('sha256').update(path).update('\0').update(bytes).digest('hex')
let generated
let topicSchema = null
try {
  const promptSource = readFileSync(resolve(root, promptPath))
  const schemaSource = readFileSync(resolve(root, schemaPath))
  const promptText = promptSource.toString('utf8').replace(/^<!--[^\r\n]*-->\r?\n/, '').trim()
  const schema = JSON.parse(schemaSource.toString('utf8'))
  const valid = schema?.type === 'object' && schema.additionalProperties === false &&
    JSON.stringify(schema.required) === JSON.stringify(['topics','identityDecisions','assignments']) && schema.properties?.identityDecisions?.items?.additionalProperties === false && schema.properties?.assignments?.items?.additionalProperties === false &&
    schema.properties?.assignments?.items?.properties?.relevance?.enum?.join(',') === 'action,awareness,unrelated,unknown' &&
    schema.properties?.assignments?.items?.properties?.relation?.enum?.join(',') === 'about,repost,uncertain'
  if (!valid || !promptText || /\{\{[^}]+\}\}/.test(promptText)) throw new Error('bundle_contract_invalid')
  topicSchema = schema
  const promptHash = hash(promptPath, promptSource)
  const schemaHash = hash(schemaPath, schemaSource)
  generated = `// Generated by scripts/build-group-topics-prompts.mjs; do not hand edit.
export const GROUP_TOPICS_BUNDLE_ENABLED = true
export const GROUP_TOPICS_PROMPT_VERSION = 'group-topics-v5'
export const GROUP_TOPICS_SCHEMA_VERSION = 'topic-output-v4'
export const GROUP_TOPICS_PROMPT = ${JSON.stringify(promptText)}
export const GROUP_TOPICS_JSON_SCHEMA = ${JSON.stringify(schema)} as const
export const GROUP_TOPICS_PROMPT_HASH = '${promptHash}'
export const GROUP_TOPICS_SCHEMA_HASH = '${schemaHash}'
`
} catch (error) {
  process.stderr.write(`groupTopics prompt bundle: topic sources invalid, bundle disabled (${error instanceof Error ? error.message : String(error)})\n`)
  generated = `// Generated by scripts/build-group-topics-prompts.mjs; invalid sources fail closed.
export const GROUP_TOPICS_BUNDLE_ENABLED = false
export const GROUP_TOPICS_PROMPT_VERSION = 'group-topics-v5'
export const GROUP_TOPICS_SCHEMA_VERSION = 'topic-output-v4'
export const GROUP_TOPICS_PROMPT = ''
export const GROUP_TOPICS_JSON_SCHEMA = {} as const
export const GROUP_TOPICS_PROMPT_HASH = ''
export const GROUP_TOPICS_SCHEMA_HASH = ''
`
}

// Combined todo+topic output: the schema is composed here from the two existing sources (no third hand-written copy).
// Failure only disables the combined bundle; the v4/v3 topic bundle above is unaffected.
const combinedHeader = `export const COMBINED_PROMPT_VERSION = '${combinedPromptVersion}'
export const COMBINED_SCHEMA_VERSION = '${combinedSchemaVersion}'
`
let combined
try {
  if (!topicSchema) throw new Error('topic_bundle_invalid')
  // New file only: normalize to LF so the text and its hash do not depend on the checkout's line endings (the v4/v3 sources above are deliberately left untouched).
  const sectionSource = Buffer.from(readFileSync(resolve(root, combinedSectionPath), 'utf8').replace(/\r\n?/g, '\n'), 'utf8')
  const sectionText = sectionSource.toString('utf8').replace(/^<!--[^\r\n]*-->\r?\n/, '').trim()
  const loaded = spawnSync(process.execPath, ['--no-warnings', '--experimental-strip-types', '--experimental-loader=./scripts/ts-test-loader.mjs', '--input-type=module', '-e',
    `import('./${todoSchemaSourcePath}').then((m) => process.stdout.write(JSON.stringify(m.EXTRACT_JSON_SCHEMA.schema)))`], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 24 })
  if (loaded.status !== 0) throw new Error('todo_schema_unreadable')
  const todoSchema = JSON.parse(loaded.stdout)
  const todoValid = todoSchema?.type === 'object' && todoSchema.additionalProperties === false && Array.isArray(todoSchema.required) &&
    todoSchema.required.includes('newTodos') && todoSchema.required.includes('importance')
  if (!todoValid || !sectionText || /\{\{[^}]+\}\}/.test(sectionText) || !sectionText.includes('topic.targetMsgIds')) throw new Error('combined_contract_invalid')
  const combinedSchema = {
    type: 'object', additionalProperties: false, required: ['todo', 'topic'],
    properties: { todo: todoSchema, topic: { ...topicSchema, type: ['object', 'null'] } }
  }
  const combinedSchemaBytes = Buffer.from(JSON.stringify(combinedSchema), 'utf8')
  combined = `export const COMBINED_BUNDLE_ENABLED = true
${combinedHeader}export const COMBINED_TOPIC_SECTION = ${JSON.stringify(sectionText)}
export const COMBINED_JSON_SCHEMA = ${JSON.stringify(combinedSchema)} as const
export const COMBINED_PROMPT_HASH = '${hash(combinedSectionPath, sectionSource)}'
export const COMBINED_SCHEMA_HASH = '${hash(combinedSchemaPath, combinedSchemaBytes)}'
`
} catch (error) {
  process.stderr.write(`groupTopics prompt bundle: combined sources invalid, combined bundle disabled (${error instanceof Error ? error.message : String(error)})\n`)
  combined = `export const COMBINED_BUNDLE_ENABLED = false
${combinedHeader}export const COMBINED_TOPIC_SECTION = ''
export const COMBINED_JSON_SCHEMA = {} as const
export const COMBINED_PROMPT_HASH = ''
export const COMBINED_SCHEMA_HASH = ''
`
}
generated += combined
if (process.argv.includes('--check')) {
  if (readFileSync(resolve(root, outputPath), 'utf8') !== generated) {
    process.stderr.write('groupTopics prompt bundle is stale; run npm run build\n')
    process.exitCode = 1
  }
} else writeFileSync(resolve(root, outputPath), generated, 'utf8')
