import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = process.cwd()
const promptPath = 'src/main/features/groupTopics/prompts/chat-classify.md'
const schemaPath = 'src/main/features/groupTopics/prompts/topic-output.schema.json'
const outputPath = 'src/main/features/groupTopics/prompts/bundle.ts'
const hash = (path, bytes) => createHash('sha256').update(path).update('\0').update(bytes).digest('hex')
let generated
try {
  const promptSource = readFileSync(resolve(root, promptPath))
  const schemaSource = readFileSync(resolve(root, schemaPath))
  const promptText = promptSource.toString('utf8').replace(/^<!--[^\r\n]*-->\r?\n/, '').trim()
  const schema = JSON.parse(schemaSource.toString('utf8'))
  const valid = schema?.type === 'object' && schema.additionalProperties === false &&
    JSON.stringify(schema.required) === JSON.stringify(['topics','assignments']) && schema.properties?.assignments?.items?.additionalProperties === false &&
    schema.properties?.assignments?.items?.properties?.relevance?.enum?.join(',') === 'action,awareness,unrelated,unknown' &&
    schema.properties?.assignments?.items?.properties?.relation?.enum?.join(',') === 'about,repost,uncertain'
  if (!valid || !promptText || /\{\{[^}]+\}\}/.test(promptText)) throw new Error('bundle_contract_invalid')
  const promptHash = hash(promptPath, promptSource)
  const schemaHash = hash(schemaPath, schemaSource)
  generated = `// Generated by scripts/build-group-topics-prompts.mjs; do not hand edit.
export const GROUP_TOPICS_BUNDLE_ENABLED = true
export const GROUP_TOPICS_PROMPT_VERSION = 'group-topics-v2'
export const GROUP_TOPICS_SCHEMA_VERSION = 'topic-output-v1'
export const GROUP_TOPICS_PROMPT = ${JSON.stringify(promptText)}
export const GROUP_TOPICS_JSON_SCHEMA = ${JSON.stringify(schema)} as const
export const GROUP_TOPICS_PROMPT_HASH = '${promptHash}'
export const GROUP_TOPICS_SCHEMA_HASH = '${schemaHash}'
`
} catch {
  generated = `// Generated by scripts/build-group-topics-prompts.mjs; invalid sources fail closed.
export const GROUP_TOPICS_BUNDLE_ENABLED = false
export const GROUP_TOPICS_PROMPT_VERSION = 'group-topics-v2'
export const GROUP_TOPICS_SCHEMA_VERSION = 'topic-output-v1'
export const GROUP_TOPICS_PROMPT = ''
export const GROUP_TOPICS_JSON_SCHEMA = {} as const
export const GROUP_TOPICS_PROMPT_HASH = ''
export const GROUP_TOPICS_SCHEMA_HASH = ''
`
}
if (process.argv.includes('--check')) {
  if (readFileSync(resolve(root, outputPath), 'utf8') !== generated) {
    process.stderr.write('groupTopics prompt bundle is stale; run npm run build\n')
    process.exitCode = 1
  }
} else writeFileSync(resolve(root, outputPath), generated, 'utf8')
